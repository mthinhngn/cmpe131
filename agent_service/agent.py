"""Typed state shared by the Course Radar graph and browser action protocol.

Runtime contracts: docs/COURSE_ACTION_INTERPRETATION.md.
Required reads must finish successfully before a dependent website action.
"""

from typing import Annotated, Any, Literal, TypedDict

from langchain_core.messages import AnyMessage, SystemMessage, ToolMessage
from langchain_core.tools import tool
from langchain_groq import ChatGroq
from langgraph.graph import END, START, StateGraph, add_messages


# Identifies a calendar term and where its information came from.
class AcademicTerm(TypedDict):
    id: str  # For example, "fall-2026".
    season: Literal["spring", "summer", "fall", "winter"]  # Academic season.
    year: int  # Calendar year, such as 2026.
    source: Literal["configured", "user", "web"]  # Provider of this term information.


# Describes one course assigned to a personal planner slot.
class PlanEntry(TypedDict):
    course_id: str  # Catalog ID of the planned course.
    semester_slot: int | str  # Existing numbered planner slot; not a calendar term.
    status: Literal["planned", "in-progress"]  # Whether the course is planned or underway.


# Captures the website state used to interpret and validate a request.
class AppContext(TypedDict):
    # A fresh snapshot supplied by the website, not generated by the model.
    program_id: str  # Currently selected degree program.
    page: str  # Current internal website route.
    selected_course_id: str | None  # Visible course referenced by "this course".
    completed_course_ids: list[str]  # Courses the user has marked completed.
    plan: list[PlanEntry]  # Current personal semester assignments.
    term_to_slot: dict[str, int]  # Empty until a mapping is provided.
    starting_term: str | None  # Browser-local profile: Semester 1.
    revision: str  # Proposed integration version for detecting stale reads.


# Represents a catalog course found by a read tool.
class CourseMatch(TypedDict):
    course_id: str  # Actual catalog ID from a successful lookup.
    code: str  # Display course code, such as "CS 146".
    title: str  # Catalog course title.
    program_id: str  # Program associated with this catalog match.


# Tracks one required read and the evidence that it finished.
class ReadRequirement(TypedDict):
    # Tool execution supplies completion evidence before an action is allowed.
    key: str  # Prerequisite identifier, such as "course_lookup".
    tool: Literal["find_course", "get_course", "get_plan", "resolve_term"]  # Required read tool.
    arguments: dict[str, Any]  # Tool-specific schemas will narrow this later.
    status: Literal["pending", "succeeded", "failed"]  # Actual read execution outcome.
    tool_call_id: str | None  # Tool call supplying completion evidence.
    context_revision: str | None  # Website version used by this read, if applicable.


# Supplies identifiers shared by every website action.
class ActionMetadata(TypedDict):
    action_id: str  # Unique action identifier used to detect duplicate dispatches.
    tool_call_id: str  # Model tool call that requested this action.
    expected_revision: str  # Website version the action was validated against.


# Requests opening a resolved course inside Course Radar.
class OpenCourseAction(ActionMetadata):
    kind: Literal["open_course"]  # Selects the open-course action handler.
    course_id: str  # Catalog course to open.


# Requests adding a resolved course to a mapped semester slot.
class AddCourseAction(ActionMetadata):
    kind: Literal["add_course_to_plan"]  # Selects the add-to-plan action handler.
    course_id: str  # Catalog course to add.
    target_term: AcademicTerm | None  # Unnecessary for an explicit numbered slot.
    semester_slot: int | str  # Numbered planner slot mapped to the target term.


class ChangePlanAction(ActionMetadata):
    kind: Literal["remove_course_from_plan", "move_course_in_plan"]
    course_id: str
    source_semester_slot: int | str | None  # User's optional source constraint.
    previous_semester_slot: int | str | str  # Actual source from the fresh planner read.
    previous_status: Literal["planned", "in-progress"]
    semester_slot: int | str | None  # Destination for move; unused for removal.
    target_term: AcademicTerm | None


PendingAction = OpenCourseAction | AddCourseAction | ChangePlanAction


# Records the website's confirmed outcome for a dispatched action.
class ActionResult(TypedDict):
    # Only a matching website acknowledgement establishes the outcome.
    action_id: str  # Dispatched action acknowledged by the website.
    tool_call_id: str  # Tool call receiving this result.
    status: Literal["succeeded", "failed"]  # Confirmed execution outcome.
    code: str  # Structured outcome, such as "course_added" or "stale_context".
    message: str  # Safe explanation of the outcome for the model and user.
    applied_revision: str | None  # Website version after successful execution.


# Shares conversation, read evidence, and action progress between graph nodes.
class AgentState(TypedDict):
    kimi_decision: dict
    kimi_observations: list[dict]
    kimi_count: int
    kimi_preferences: dict
    kimi_history: list[dict]
    calendar_cache: dict | None
    pending_clarification: dict | None
    offering_evidence: dict | None
    resolved_slot: int | str | None
    resolved_source_slot: int | str | None
    web_handoff: dict[str, Any] | None  # Typed/validated at the separate agent boundary.
    # Conversation with the user, model tool calls, and tool responses.
    messages: Annotated[list[AnyMessage], add_messages]

    # Current website selection and personal course plan.
    app_context: AppContext

    # Verified public calendar context; absent for requests that do not need it.
    current_term: AcademicTerm | None

    # Requested term, such as Spring 2027; None until resolved or if unnecessary.
    target_term: AcademicTerm | None

    # Catalog records matching the user's course query.
    course_matches: list[CourseMatch]

    # Reads required for the action and their actual execution status.
    read_requirements: list[ReadRequirement]

    # One validated action awaiting website execution or acknowledgement.
    pending_action: PendingAction | None

    # Confirmed action outcome; None while no acknowledgement has arrived.
    action_result: ActionResult | None

    # Model/tool iterations in this request, used by future routing limits.
    step_count: int

    # Explicit branch chosen by a node and checked by Python routing.
    decision: Literal["read_tools", "read_more", "validate_action", "execute_action", "respond"] | None

    # Ordered actions extracted from the user's request by the model.
    steps: list[dict[str, Any]]

    # Index of the next requested action, advanced only after acknowledgement.
    action_index: int

    # Confirmed results from this request, preserved when a later step fails.
    outcomes: list[dict[str, Any]]

    # User-facing clarification, error, or final response.
    reply: str

    # Stops routing on an actual read, validation, or execution failure.
    error: str | None

    # Ordered execution events exposed for manual testing and trace inspection.
    events: list[dict[str, Any]]
